def as_records():
    """Normalised dicts, shaped like the discovered catalogue entries."""
    out = []
    seen = set()
    for name, url, jobs, pricing, tier, tagline in PLATFORMS:
        slug = name.lower().replace(" ", "-").replace(".", "-").replace("+", "-")
        slug = "".join(c for c in slug if c.isalnum() or c == "-")
        if slug in seen:
            slug += "-platform"
        seen.add(slug)
        out.append({
            "id": slug,
            "name": name,
            "repo": "",
            "url": url,
            "tagline": tagline,
            "jobs": jobs,
            "licence": "Proprietary",
            "stars": 0,
            # tier stands in for prominence when ranking against libraries
            "weight": {1: 90000, 2: 30000, 3: 8000}[tier],
            "pushed": "",
            "lang": "",
            "detail": 1,
            "kind": "platform",
            "pricing": pricing,
            "tier": tier,
        })
    return out


