def gql(chunk):
    parts = []
    for i, (_, _, repo, *_) in enumerate(chunk):
        owner, name = repo.split("/")
        parts.append(
            f'r{i}: repository(owner:"{owner}", name:"{name}")'
            "{ nameWithOwner stargazerCount pushedAt isArchived"
            " primaryLanguage{name} licenseInfo{spdxId} }"
        )
    return "query{" + " ".join(parts) + "}"


def fetch_meta(repos):
    meta = {}
    repos = [r for r in repos if r]
    chunks = [repos[i:i + 40] for i in range(0, len(repos), 40)]
    for chunk in chunks:
        q = gql([(None, None, r) for r in chunk])
        out = subprocess.run(
            ["gh", "api", "graphql", "-f", f"query={q}"],
            capture_output=True, text=True,
        )
        if out.returncode != 0:
            print("  gh error:", out.stderr[:300])
            continue
        data = json.loads(out.stdout).get("data", {}) or {}
        for i, repo in enumerate(chunk):
            node = data.get(f"r{i}")
            if node:
                meta[repo] = node
    return meta


